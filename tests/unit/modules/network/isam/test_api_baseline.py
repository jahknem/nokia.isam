"""Public API freeze for the 1.x line: module inventory and every module's argument spec.

Each module's main() is run until it builds its AnsibleModule; the keyword
arguments it passes (argument_spec, mutually_exclusive, required_if,
required_one_of, required_together, required_by, supports_check_mode) are
normalized and hashed, per module and per top-level option, and compared with
api_baseline.json. Any difference fails the test: a removed or renamed module
or option, a changed type, default, choice, alias, no_log flag or constraint.

To change the API on purpose (and record it in the changelog), regenerate the
baseline and commit it with the change:

    ISAM_UPDATE_API_BASELINE=1 TESTPATH=tests/unit/modules/network/isam/test_api_baseline.py .venv/bin/tox -e py312

With ISAM_UPDATE_API_BASELINE set, the baseline is rewritten and the comparison
is skipped.
"""
import hashlib
import importlib
import json
import os
import pathlib

import pytest
from ansible.module_utils import basic

from .isam_module import set_module_args

BASELINE = pathlib.Path(__file__).with_name("api_baseline.json")
MODULES_DIR = pathlib.Path(__file__).resolve().parents[5] / "plugins" / "modules"
UPDATE_ENV = "ISAM_UPDATE_API_BASELINE"
CONSTRAINTS = ("mutually_exclusive", "required_if", "required_one_of", "required_together", "required_by",
               "supports_check_mode")


class _Captured(Exception):
    def __init__(self, kwargs):
        super(_Captured, self).__init__("AnsibleModule constructed")
        self.kwargs = kwargs


def _normalize(value):
    """JSON-stable form: dict keys sorted by json.dumps, callables by name, tuples as lists."""
    if isinstance(value, dict):
        return dict((str(key), _normalize(item)) for key, item in value.items())
    if isinstance(value, (list, tuple)):
        return [_normalize(item) for item in value]
    if isinstance(value, (set, frozenset)):
        return sorted(_normalize(item) for item in value)
    if callable(value):
        return "<callable %s>" % getattr(value, "__name__", type(value).__name__)
    return value


def _digest(value):
    return hashlib.sha256(json.dumps(_normalize(value), sort_keys=True).encode("utf-8")).hexdigest()


def module_names():
    return sorted(path.stem for path in MODULES_DIR.glob("*.py") if path.stem != "__init__")


def capture_module_api(name, monkeypatch):
    """The keyword arguments module `name` passes to AnsibleModule."""
    def fake_init(self, *args, **kwargs):
        if args:
            kwargs = dict(kwargs, argument_spec=args[0])
        raise _Captured(kwargs)

    monkeypatch.setattr(basic.AnsibleModule, "__init__", fake_init)
    set_module_args({}, True)
    module = importlib.import_module("ansible_collections.nokia.isam.plugins.modules.%s" % name)
    with pytest.raises(_Captured) as captured:
        module.main()
    kwargs = captured.value.kwargs
    api = dict((key, kwargs[key]) for key in CONSTRAINTS if key in kwargs)
    api["argument_spec"] = kwargs.get("argument_spec") or {}
    return api


def snapshot(name, monkeypatch):
    api = capture_module_api(name, monkeypatch)
    spec = api["argument_spec"]
    return {
        "sha256": _digest(api),
        "constraints": _digest(dict((key, api[key]) for key in CONSTRAINTS if key in api)),
        "options": dict((option, _digest(spec[option])) for option in sorted(spec)),
    }


def current_baseline(monkeypatch):
    return {
        "comment": "Generated by test_api_baseline.py; regenerate only for an intended API change.",
        "modules": module_names(),
        "argspecs": dict((name, snapshot(name, monkeypatch)) for name in module_names()),
    }


def _stored():
    return json.loads(BASELINE.read_text())


def test_update_baseline_on_request(monkeypatch):
    if not os.environ.get(UPDATE_ENV):
        pytest.skip("set %s=1 to regenerate api_baseline.json" % UPDATE_ENV)
    BASELINE.write_text(json.dumps(current_baseline(monkeypatch), indent=1, sort_keys=True) + "\n")


@pytest.mark.skipif(bool(os.environ.get(UPDATE_ENV)), reason="baseline is being regenerated")
def test_module_inventory_is_unchanged():
    stored = _stored()["modules"]
    current = module_names()
    assert current == stored, "modules added %s, removed %s (see the module docstring to update the baseline)" % (
        sorted(set(current) - set(stored)), sorted(set(stored) - set(current)))


@pytest.mark.skipif(bool(os.environ.get(UPDATE_ENV)), reason="baseline is being regenerated")
@pytest.mark.parametrize("name", module_names())
def test_module_argspec_is_unchanged(name, monkeypatch):
    stored = _stored()["argspecs"].get(name)
    assert stored is not None, "%s has no baseline entry" % name
    current = snapshot(name, monkeypatch)
    if current["sha256"] == stored["sha256"]:
        return
    changed = sorted(option for option in set(current["options"]) | set(stored["options"])
                     if current["options"].get(option) != stored["options"].get(option))
    detail = "options changed/added/removed: %s" % changed if changed else "constraints changed"
    if changed and current["constraints"] != stored["constraints"]:
        detail += "; constraints changed"
    pytest.fail("%s argument spec differs from api_baseline.json (%s). If intended, regenerate the baseline "
                "(see test_api_baseline.py) and note the API change in the changelog." % (name, detail), pytrace=False)


def test_snapshot_detects_changes(monkeypatch):
    """The comparison really sees option-level and constraint-level edits."""
    base = {"argument_spec": {"config": {"type": "dict", "options": {"a": {"type": "str"}}}, "state": {"choices": ["merged"]}},
            "mutually_exclusive": [["config", "running_config"]]}
    renamed = json.loads(json.dumps(base))
    renamed["argument_spec"]["config"]["options"]["b"] = renamed["argument_spec"]["config"]["options"].pop("a")
    loosened = dict(base, mutually_exclusive=[])
    assert len(set([_digest(base), _digest(renamed), _digest(loosened)])) == 3
    assert _digest(base["argument_spec"]["state"]) == _digest(renamed["argument_spec"]["state"])
