#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Generate the standard resource-module RETURN docs (before, after, commands, ...).

Every resource module returns the netcommon state results: C(before), C(after) and
C(commands) for the action states, C(gathered), C(rendered) and C(parsed) for the others.
Their documentation is written once here and generated into each module's RETURN block
between the BEGIN/END markers below, shaped by the module's own DOCUMENTATION (the
I(state) choices it supports and the type of I(config)). Return-section doc fragments
only work on ansible-core 2.20+ (see tools/sync_read_outcomes_docs.py), so the text is
inlined rather than referenced. A module-specific C(commands)/C(rendered) sample is kept.

    python tools/sync_resource_return_docs.py          # rewrite the modules
    python tools/sync_resource_return_docs.py --check  # verify only (CI)
"""

import ast
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / "plugins" / "modules"
BEGIN = "# BEGIN resource_returns (generated by tools/sync_resource_return_docs.py; do not edit)"
END = "# END resource_returns"
KEYS = ("before", "after", "commands", "rendered", "gathered", "parsed")
ACTION = ("merged", "replaced", "overridden", "deleted")

TEXT = {
    "before": (
        ["The configuration before the module ran, in the format of I(config).",
         "With I(running_config) (offline preview) it is the supplied configuration."],
        "when I(state) is ACTION_STATES",
    ),
    "after": (
        ["The configuration read back from the device after the commands were sent, in the format"
         " of I(config). In check mode nothing is sent, so it shows the unchanged configuration."],
        "when I(state) is ACTION_STATES, commands were generated and no I(running_config) was given",
    ),
    "commands": (
        ["The commands sent to the device (in check mode: that would be sent).",
         "With I(running_config) (offline preview) they are rendered only, never sent."],
        "when I(state) is ACTION_STATES",
    ),
    "rendered": (
        ["The commands rendered from I(config) in device-native format, without a device (offline)."],
        "when I(state) is C(rendered)",
    ),
    "gathered": (
        ["The configuration read from the device, in the format of I(config)."],
        "when I(state) is C(gathered)",
    ),
    "parsed": (
        ["The I(running_config) text parsed into the format of I(config), without a device."],
        "when I(state) is C(parsed)",
    ),
}
STATE_OF = {"before": ACTION, "after": ACTION, "commands": ACTION,
            "rendered": ("rendered",), "gathered": ("gathered",), "parsed": ("parsed",)}


def _assignment(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == name:
            return node
    return None


def _states_list(states):
    names = ["C(%s)" % state for state in states]
    return names[0] if len(names) == 1 else "%s or %s" % (", ".join(names[:-1]), names[-1])


def expected_entries(doc, existing):
    options = doc.get("options") or {}
    states = (options.get("state") or {}).get("choices") or []
    config_type = (options.get("config") or {}).get("type", "str")
    actions = [state for state in ACTION if state in states]
    entries = {}
    for key in KEYS:
        if not any(state in states for state in STATE_OF[key]):
            continue
        description, returned = TEXT[key]
        entry = {"description": list(description),
                 "returned": returned.replace("ACTION_STATES", _states_list(actions) if actions else "")}
        if key in ("commands", "rendered"):
            entry.update(type="list", elements="str")
            sample = (existing.get(key) or {}).get("sample")
            if isinstance(sample, list) and sample and all(isinstance(item, str) for item in sample) \
                    and not any(item.startswith("sample command") for item in sample):
                entry["sample"] = sample
        else:
            entry["type"] = config_type
        entries[key] = entry
    return entries


def _chunks(text):
    """Top-level YAML chunks of a RETURN body: [(key or None, lines)]; comments stick to the next key."""
    chunks, pending, current = [], [], None
    in_marker = None
    for line in text.split("\n"):
        if in_marker is not None:
            in_marker.append(line)
            if line.startswith("# END "):
                chunks.append(("#marker", in_marker))
                in_marker = None
            continue
        if line.startswith("# BEGIN "):
            if current:
                chunks.append(current)
                current = None
            in_marker = pending + [line]
            pending = []
            continue
        match = re.match(r"^([A-Za-z_][\w-]*):", line)
        if match:
            if current:
                chunks.append(current)
            current = (match.group(1), pending + [line])
            pending = []
        elif line.startswith("#") or not line.strip():
            pending.append(line)
        else:
            if current is None:
                current = (None, pending)
                pending = []
            current[1].append(line)
    if current:
        chunks.append(current)
    if pending:
        chunks.append((None, pending))
    return chunks


def render_block(entries):
    body = yaml.safe_dump(entries, default_flow_style=False, sort_keys=False, width=100, allow_unicode=True)
    return "%s\n%s%s" % (BEGIN, body, END)


def sync_text(source):
    """(new_source, changed) for one module source; unchanged when it is not a resource module."""
    tree = ast.parse(source)
    doc_node, ret_node = _assignment(tree, "DOCUMENTATION"), _assignment(tree, "RETURN")
    doc = yaml.safe_load(doc_node.value.value) or {}
    if not set(((doc.get("options") or {}).get("state") or {}).get("choices") or []) & set(
            ACTION + ("rendered", "parsed")):
        return source, False
    if "config" not in (doc.get("options") or {}):
        return source, False
    body = ret_node.value.value
    existing = yaml.safe_load(body) or {}
    block = render_block(expected_entries(doc, existing))
    kept = []
    for key, lines in _chunks(body.strip("\n")):
        if key in KEYS:
            continue
        if key == "#marker" and any(line.startswith(BEGIN) for line in lines):
            continue
        kept.append("\n".join(lines).strip("\n"))
    new_body = "\n".join(part for part in kept if part.strip()) + ("\n" if kept else "") + block
    new_body = new_body.strip("\n")
    yaml.safe_load(new_body)
    lines = source.split("\n")
    first, last = ret_node.lineno - 1, ret_node.end_lineno - 1
    opening = re.match(r"^(RETURN = r?)(\"\"\"|''')", lines[first])
    quote = opening.group(2)
    new_lines = lines[:first] + ["%s%s" % (opening.group(1), quote)] + new_body.split("\n") + [quote] + lines[last + 1:]
    new_source = "\n".join(new_lines)
    return new_source, new_source != source


def main(argv):
    check = "--check" in argv
    problems = []
    for path in sorted(MODULES.glob("*.py")):
        if path.name == "__init__.py":
            continue
        source = path.read_text()
        new_source, changed = sync_text(source)
        if not changed:
            continue
        if check:
            problems.append("%s: standard RETURN docs out of sync" % path.name)
        else:
            path.write_text(new_source)
            print("updated %s" % path.name)
    for problem in problems:
        print("PROBLEM: %s" % problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
